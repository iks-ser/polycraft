#!/usr/bin/env python3
"""Generates Polycraft's placeholder low-poly models and ground texture.

Run from anywhere:  python3 tools/generate_assets.py

Outputs (flat-shaded Wavefront OBJ + MTL, Y-up, 1 unit = 1 metre):
    assets/models/tree_pine.obj / .mtl
    assets/models/tree_oak.obj  / .mtl
    assets/models/bush_small.obj / .mtl
    assets/models/bush_berry.obj / .mtl
    assets/textures/grass.png

Only the standard library is needed. Output is deterministic (fixed RNG seeds),
so re-running produces identical files. Godot imports the OBJ files directly and
turns the MTL entries into StandardMaterial3D surfaces.
"""

import math
import random
import struct
import zlib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MODELS_DIR = ROOT / "assets" / "models"
TEXTURES_DIR = ROOT / "assets" / "textures"

# --------------------------------------------------------------------------- #
# Materials (sRGB, 0..1)
# --------------------------------------------------------------------------- #
MATERIALS = {
    "bark": (0.36, 0.24, 0.14),
    "pine_leaves": (0.13, 0.38, 0.22),
    "oak_leaves": (0.30, 0.55, 0.20),
    "bush_leaves": (0.25, 0.50, 0.22),
    "berry": (0.78, 0.12, 0.18),
}


# --------------------------------------------------------------------------- #
# Tiny vector helpers
# --------------------------------------------------------------------------- #
def sub(a, b):
    return (a[0] - b[0], a[1] - b[1], a[2] - b[2])


def add(a, b):
    return (a[0] + b[0], a[1] + b[1], a[2] + b[2])


def cross(a, b):
    return (
        a[1] * b[2] - a[2] * b[1],
        a[2] * b[0] - a[0] * b[2],
        a[0] * b[1] - a[1] * b[0],
    )


def dot(a, b):
    return a[0] * b[0] + a[1] * b[1] + a[2] * b[2]


def length(a):
    return math.sqrt(dot(a, a))


def normalize(a):
    l = length(a)
    return (a[0] / l, a[1] / l, a[2] / l)


# --------------------------------------------------------------------------- #
# Model container + OBJ writer
# --------------------------------------------------------------------------- #
class Model:
    def __init__(self, name):
        self.name = name
        self.tris = {}  # material name -> list of (a, b, c) vertex tuples

    def add_tri(self, material, a, b, c, inside):
        """Adds a triangle, flipping its winding so it faces away from `inside`.

        Every primitive below is convex, so a point inside it is enough to
        guarantee outward-facing (counter-clockwise) triangles.
        """
        n = cross(sub(b, a), sub(c, a))
        if length(n) < 1e-9:
            return  # degenerate (e.g. cone apex ring)
        centroid = ((a[0] + b[0] + c[0]) / 3, (a[1] + b[1] + c[1]) / 3, (a[2] + b[2] + c[2]) / 3)
        if dot(n, sub(centroid, inside)) < 0:
            b, c = c, b
        self.tris.setdefault(material, []).append((a, b, c))

    def triangle_count(self):
        return sum(len(t) for t in self.tris.values())

    def write(self, directory):
        directory.mkdir(parents=True, exist_ok=True)
        used = list(self.tris.keys())

        # --- MTL ---
        mtl = [f"# {self.name} materials - generated by tools/generate_assets.py"]
        for mat in used:
            r, g, b = MATERIALS[mat]
            mtl += [
                f"newmtl {mat}",
                f"Kd {r:.4f} {g:.4f} {b:.4f}",
                "Ks 0.0 0.0 0.0",  # non-metallic
                "Ns 0.0",  # fully rough -> matte, low-poly look
                "d 1.0",
                "",
            ]
        (directory / f"{self.name}.mtl").write_text("\n".join(mtl), encoding="utf-8", newline="\n")

        # --- OBJ (one normal per face => flat shading) ---
        vertex_index = {}
        normals = []
        face_lines = []
        for mat in used:
            face_lines.append(f"usemtl {mat}")
            face_lines.append("s off")
            for a, b, c in self.tris[mat]:
                n = normalize(cross(sub(b, a), sub(c, a)))
                normals.append(n)
                ni = len(normals)
                idx = []
                for v in (a, b, c):
                    key = (round(v[0], 5), round(v[1], 5), round(v[2], 5))
                    if key not in vertex_index:
                        vertex_index[key] = len(vertex_index) + 1
                    idx.append(vertex_index[key])
                face_lines.append(f"f {idx[0]}//{ni} {idx[1]}//{ni} {idx[2]}//{ni}")

        obj = [
            f"# {self.name} - generated by tools/generate_assets.py",
            f"mtllib {self.name}.mtl",
            f"o {self.name}",
        ]
        obj += [f"v {x:.5f} {y:.5f} {z:.5f}" for (x, y, z) in vertex_index]
        obj += [f"vn {x:.5f} {y:.5f} {z:.5f}" for (x, y, z) in normals]
        obj += face_lines
        (directory / f"{self.name}.obj").write_text("\n".join(obj) + "\n", encoding="utf-8", newline="\n")


# --------------------------------------------------------------------------- #
# Primitives
# --------------------------------------------------------------------------- #
def frustum(model, mat, y0, y1, r0, r1, sides, rot=0.0, cx=0.0, cz=0.0, cap_bottom=True, cap_top=True):
    """Cylinder / cone / truncated cone along +Y. r1 == 0 gives a cone."""
    angles = [rot + 2 * math.pi * i / sides for i in range(sides)]
    ring0 = [(cx + r0 * math.cos(a), y0, cz + r0 * math.sin(a)) for a in angles]
    has_top_ring = r1 > 1e-6
    ring1 = [(cx + r1 * math.cos(a), y1, cz + r1 * math.sin(a)) for a in angles]
    apex = (cx, y1, cz)
    bottom_center = (cx, y0, cz)
    inside = (cx, y0 + (y1 - y0) * 0.4, cz)

    for i in range(sides):
        j = (i + 1) % sides
        if has_top_ring:
            model.add_tri(mat, ring0[i], ring0[j], ring1[j], inside)
            model.add_tri(mat, ring0[i], ring1[j], ring1[i], inside)
        else:
            model.add_tri(mat, ring0[i], ring0[j], apex, inside)
        if cap_bottom:
            model.add_tri(mat, bottom_center, ring0[i], ring0[j], inside)
        if cap_top and has_top_ring:
            model.add_tri(mat, apex, ring1[i], ring1[j], inside)


def _icosphere(subdivisions):
    t = (1.0 + math.sqrt(5.0)) / 2.0
    verts = [
        (-1, t, 0), (1, t, 0), (-1, -t, 0), (1, -t, 0),
        (0, -1, t), (0, 1, t), (0, -1, -t), (0, 1, -t),
        (t, 0, -1), (t, 0, 1), (-t, 0, -1), (-t, 0, 1),
    ]
    verts = [normalize(v) for v in verts]
    faces = [
        (0, 11, 5), (0, 5, 1), (0, 1, 7), (0, 7, 10), (0, 10, 11),
        (1, 5, 9), (5, 11, 4), (11, 10, 2), (10, 7, 6), (7, 1, 8),
        (3, 9, 4), (3, 4, 2), (3, 2, 6), (3, 6, 8), (3, 8, 9),
        (4, 9, 5), (2, 4, 11), (6, 2, 10), (8, 6, 7), (9, 8, 1),
    ]
    for _ in range(subdivisions):
        cache = {}

        def midpoint(a, b):
            key = (min(a, b), max(a, b))
            if key not in cache:
                m = normalize(((verts[a][0] + verts[b][0]) / 2,
                               (verts[a][1] + verts[b][1]) / 2,
                               (verts[a][2] + verts[b][2]) / 2))
                verts.append(m)
                cache[key] = len(verts) - 1
            return cache[key]

        new_faces = []
        for a, b, c in faces:
            ab, bc, ca = midpoint(a, b), midpoint(b, c), midpoint(c, a)
            new_faces += [(a, ab, ca), (b, bc, ab), (c, ca, bc), (ab, bc, ca)]
        faces = new_faces
    return verts, faces


def blob(model, mat, center, radius, rng, scale=(1.0, 1.0, 1.0), subdivisions=1, jitter=0.12):
    """Lumpy low-poly sphere used for foliage and bushes."""
    verts, faces = _icosphere(subdivisions)
    placed = []
    for v in verts:
        r = radius * (1.0 + rng.uniform(-jitter, jitter))
        placed.append((
            center[0] + v[0] * r * scale[0],
            center[1] + v[1] * r * scale[1],
            center[2] + v[2] * r * scale[2],
        ))
    for a, b, c in faces:
        model.add_tri(mat, placed[a], placed[b], placed[c], center)


def octahedron(model, mat, center, radius):
    cx, cy, cz = center
    px, nx = (cx + radius, cy, cz), (cx - radius, cy, cz)
    py, ny = (cx, cy + radius, cz), (cx, cy - radius, cz)
    pz, nz = (cx, cy, cz + radius), (cx, cy, cz - radius)
    for a, b, c in [
        (py, px, pz), (py, pz, nx), (py, nx, nz), (py, nz, px),
        (ny, pz, px), (ny, nx, pz), (ny, nz, nx), (ny, px, nz),
    ]:
        model.add_tri(mat, a, b, c, center)


# --------------------------------------------------------------------------- #
# Models
# --------------------------------------------------------------------------- #
def make_tree_pine():
    m = Model("tree_pine")
    frustum(m, "bark", 0.0, 4.5, 0.30, 0.12, 6)
    # Three stacked cones, each rotated a bit so the silhouettes don't line up.
    frustum(m, "pine_leaves", 1.9, 3.9, 1.55, 0.0, 7, rot=0.0)
    frustum(m, "pine_leaves", 3.1, 5.1, 1.20, 0.0, 7, rot=math.radians(25))
    frustum(m, "pine_leaves", 4.3, 6.4, 0.80, 0.0, 7, rot=math.radians(50))
    return m


def make_tree_oak():
    rng = random.Random(1001)
    m = Model("tree_oak")
    frustum(m, "bark", 0.0, 3.2, 0.38, 0.24, 6)
    blob(m, "oak_leaves", (0.0, 4.0, 0.0), 1.9, rng, scale=(1.0, 0.85, 1.0), subdivisions=1, jitter=0.12)
    blob(m, "oak_leaves", (1.0, 3.3, 0.5), 1.2, rng, subdivisions=1, jitter=0.12)
    blob(m, "oak_leaves", (-0.9, 3.5, -0.7), 1.3, rng, subdivisions=1, jitter=0.12)
    return m


def make_bush_small():
    rng = random.Random(2002)
    m = Model("bush_small")
    blob(m, "bush_leaves", (0.0, 0.38, 0.0), 0.72, rng, scale=(1.0, 0.7, 1.0), subdivisions=1, jitter=0.14)
    return m


def make_bush_berry():
    rng = random.Random(3003)
    m = Model("bush_berry")
    blob(m, "bush_leaves", (0.0, 0.42, 0.0), 0.70, rng, scale=(1.0, 0.75, 1.0), subdivisions=1, jitter=0.14)
    blob(m, "bush_leaves", (0.45, 0.30, 0.25), 0.45, rng, scale=(1.0, 0.8, 1.0), subdivisions=1, jitter=0.14)
    # Berries: little red octahedrons sitting on the upper half of the main blob.
    for _ in range(7):
        theta = rng.uniform(0, 2 * math.pi)
        phi = rng.uniform(math.radians(15), math.radians(70))  # angle from +Y
        r = 0.74
        pos = (
            r * math.sin(phi) * math.cos(theta),
            0.42 + r * 0.75 * math.cos(phi),
            r * math.sin(phi) * math.sin(theta),
        )
        octahedron(m, "berry", pos, 0.07)
    return m


# --------------------------------------------------------------------------- #
# Ground texture (tileable: 16x16 patches of slightly different greens)
# --------------------------------------------------------------------------- #
def write_png(path, width, height, rgb_rows):
    def chunk(tag, data):
        body = tag + data
        return struct.pack(">I", len(data)) + body + struct.pack(">I", zlib.crc32(body) & 0xFFFFFFFF)

    raw = b"".join(b"\x00" + bytes(row) for row in rgb_rows)
    png = b"\x89PNG\r\n\x1a\n"
    png += chunk(b"IHDR", struct.pack(">IIBBBBB", width, height, 8, 2, 0, 0, 0))
    png += chunk(b"IDAT", zlib.compress(raw, 9))
    png += chunk(b"IEND", b"")
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(png)


def make_grass_texture(path, size=64, patches=16, seed=42):
    rng = random.Random(seed)
    patch_px = size // patches
    base = (92, 150, 62)
    palette = []
    for _ in range(patches * patches):
        k = rng.uniform(0.88, 1.10)
        warm = rng.uniform(-6, 10)  # occasional yellower patch
        palette.append((
            max(0, min(255, int(base[0] * k + warm))),
            max(0, min(255, int(base[1] * k))),
            max(0, min(255, int(base[2] * k - warm * 0.5))),
        ))
    rows = []
    for y in range(size):
        row = []
        for x in range(size):
            row.extend(palette[(y // patch_px) * patches + (x // patch_px)])
        rows.append(row)
    write_png(path, size, size, rows)


# --------------------------------------------------------------------------- #
def main():
    for make in (make_tree_pine, make_tree_oak, make_bush_small, make_bush_berry):
        model = make()
        model.write(MODELS_DIR)
        print(f"{model.name}: {model.triangle_count()} triangles")
    make_grass_texture(TEXTURES_DIR / "grass.png")
    print("grass.png written")


if __name__ == "__main__":
    main()
